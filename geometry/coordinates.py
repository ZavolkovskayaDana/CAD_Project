
import math


def polar_to_cartesian(r, theta, degrees=True, x1=0.0, y1=0.0):
    """
    Преобразует полярные координаты конечной точки
    в декартовы координаты относительно начальной точки отрезка.

    r — длина отрезка;
    theta — введённый угол;
    degrees — True, если угол задан в градусах;
              False, если в радианах;
    x1, y1 — координаты начальной точки.

    Возвращает кортеж (x2, y2).
    """

    if r < 0:
        raise ValueError("Радиус не может быть отрицательным")

    # Переводим угол в радианы только при вводе в градусах.
    theta_rad = math.radians(theta) if degrees else theta

    # Вычисляем конечную точку относительно начальной.
    x2 = x1 + r * math.cos(theta_rad)
    y2 = y1 + r * math.sin(theta_rad)

    return x2, y2


def cartesian_to_polar(x, y, degrees=True, x1=0.0, y1=0.0):
    """
    Преобразует декартовы координаты точки в полярные
    относительно указанной начальной точки.

    x, y — координаты конечной точки;
    degrees — True для результата в градусах,
              False для результата в радианах;
    x1, y1 — координаты начала отсчёта.

    Возвращает кортеж (r, theta).
    """

    # Находим смещение конечной точки относительно начальной.
    dx = x - x1
    dy = y - y1

    # Вычисляем длину и направление отрезка.
    r = math.hypot(dx, dy)
    theta = math.atan2(dy, dx)

    # При необходимости переводим угол в градусы.
    if degrees:
        theta = math.degrees(theta)

    return r, theta
